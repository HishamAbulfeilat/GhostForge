#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// update-readme-routes.js — auto-generate the Web UI table in README.md
// from web-ui/routes.config.json (single source of truth)
//
// Usage: node scripts/update-readme-routes.js [--check]
//   --check: exit 1 if README is out of sync (for CI)
// ─────────────────────────────────────────────────────────────────────────────

const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const ROUTES_CONFIG = path.join(ROOT, 'web-ui/routes.config.json')
const README = path.join(ROOT, 'README.md')

const CHECK_MODE = process.argv.includes('--check')

// ── Load routes ───────────────────────────────────────────────────────────────
const config = JSON.parse(fs.readFileSync(ROUTES_CONFIG, 'utf8'))
const visible = config.routes.filter(r => !r.hidden)

// ── Generate table ────────────────────────────────────────────────────────────
const rows = visible.map(r =>
  `| \`${r.path}\` | ${r.icon} **${r.label}** | ${r.desc} |`
)

const table = [
  '| Route | Page | Description |',
  '|-------|------|-------------|',
  ...rows,
].join('\n')

const block = [
  '<!-- ROUTES:START — auto-generated by scripts/update-readme-routes.js -->',
  table,
  '<!-- ROUTES:END -->',
].join('\n')

// ── Update README ─────────────────────────────────────────────────────────────
const readme = fs.readFileSync(README, 'utf8')
const START = '<!-- ROUTES:START'
const END = '<!-- ROUTES:END -->'

const startIdx = readme.indexOf(START)
const endIdx = readme.indexOf(END)

if (startIdx === -1 || endIdx === -1) {
  // No markers yet — find the old static table and replace it
  const staticTableRegex = /(\| Route \| Description \|[\s\S]*?\n\n)/m
  const newReadme = readme.replace(staticTableRegex, block + '\n\n')
  if (newReadme === readme) {
    console.error('❌ Could not find ROUTES markers or static table in README.md')
    console.error('   Add markers manually or place them after the "### Pages" heading.')
    process.exit(1)
  }
  if (CHECK_MODE) {
    console.log('⚠  README is missing ROUTES markers. Run without --check to inject them.')
    process.exit(1)
  }
  fs.writeFileSync(README, newReadme)
  console.log('✅ README.md updated — ROUTES markers injected and table generated')
} else {
  const current = readme.slice(startIdx, endIdx + END.length)
  if (current === block) {
    console.log('✅ README.md is already up-to-date')
    process.exit(0)
  }
  if (CHECK_MODE) {
    console.error('❌ README Web UI table is out of sync with routes.config.json')
    console.error('   Run: node scripts/update-readme-routes.js')
    process.exit(1)
  }
  const updated = readme.slice(0, startIdx) + block + readme.slice(endIdx + END.length)
  fs.writeFileSync(README, updated)
  console.log(`✅ README.md updated — ${visible.length} routes synced`)
  visible.forEach(r => console.log(`   ${r.icon} ${r.path} — ${r.label}`))
}
